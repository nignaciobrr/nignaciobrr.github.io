import { test, expect } from '@playwright/test';
test('registra un traslado, persiste y registra salida y recepción',async({page})=>{
  await page.goto('/');
  await expect(page.getByText('Tu primer traslado comienza aquí')).toBeVisible();
  await page.getByRole('button',{name:'Nuevo traslado'}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Origen').selectOption('rancagua');
  await dialog.getByLabel('Destino').selectOption('quinta');
  await dialog.getByLabel('Responsable del registro').fill('Ignacio');
  await dialog.getByLabel('Tipo de carga').selectOption('Residuo peligroso');
  await expect(dialog.getByLabel('Número ONU')).toBeVisible();
  await dialog.getByLabel('Material o residuo').fill('Envases de prueba');
  await dialog.getByLabel('Cantidad').fill('25');
  await dialog.getByRole('button',{name:'Guardar traslado'}).click();
  await expect(page.getByText('Envases de prueba',{exact:true})).toBeVisible();
  await page.reload();
  await page.getByRole('button',{name:/Ver traslado CG-/}).click();
  await dialog.getByLabel('Registrado por').fill('Ana');
  await dialog.getByRole('button',{name:'Actualizar estado'}).click();
  await dialog.getByLabel('Registrado por').fill('Pedro');
  await dialog.getByLabel('Observaciones / recepción').fill('25 kg recibidos sin diferencias');
  await dialog.getByRole('button',{name:'Actualizar estado'}).click();
  await expect(dialog.getByText('Este traslado está cerrado.',{exact:false})).toBeVisible();
  await expect(dialog.getByText('Pedro · 25 kg recibidos sin diferencias')).toBeVisible();
  await dialog.getByRole('button',{name:'Cerrar',exact:true}).click();
  await page.getByLabel('Filtrar por estado').selectOption('Programado');
  await expect(page.getByText('No encontramos coincidencias')).toBeVisible();
  await page.getByRole('button',{name:'Limpiar filtros'}).click();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Exportar CSV'}).click();
  expect((await download).suggestedFilename()).toBe('clever-traslados.csv');
});
test('permite agregar sucursales y separa datos de ejemplo',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'Sucursales',exact:true}).click();
  await page.getByRole('button',{name:'Agregar sucursal'}).click();
  await page.getByLabel('Nombre de sucursal o punto').fill('Sucursal de prueba');
  await page.getByLabel('Dirección y comuna').fill('Dirección de prueba, Santiago');
  await page.getByRole('button',{name:'Guardar sucursal'}).click();
  await expect(page.getByRole('heading',{name:'Sucursal de prueba'})).toBeVisible();
  await page.getByRole('button',{name:'Vista general'}).click();
  await page.getByRole('button',{name:'Cargar ejemplos de demostración'}).click();
  await expect(page.getByText('Incluye registros ficticios de demostración.')).toBeVisible();
  await page.getByLabel('Buscar traslados').fill('DEMO-002');
  await expect(page.getByRole('button',{name:'DEMO-002 DEMO'})).toBeVisible();
  await expect(page.getByRole('button',{name:'DEMO-001 DEMO'})).toHaveCount(0);
});
test('vista móvil sin desbordamiento de página',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.getByRole('button',{name:'Cargar ejemplos de demostración'}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await expect(page.getByRole('button',{name:'Nuevo traslado'})).toBeVisible();
});
